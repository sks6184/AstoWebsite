def normalize_language(language):
    return LANGUAGE_ALIASES.get((language or "English").strip().lower(), "English")


def _localized(mapping, language):
    language = normalize_language(language)
    return mapping.get(language) or mapping.get("English") or ""


def remedy_for_planet(planet_code, role="Dasha lord", language="English"):
    planet_row = PLANETARY_BEEJ_MANTRAS.get(planet_code)
    if not planet_row:
        return {}
    language = normalize_language(language)
    deity_row = DEITY_MANTRAS[planet_row["deity_key"]]
    beej_mantra = _localized(planet_row["mantras"], language)
    beej_transliteration = planet_row["mantras"].get("English", "")
    beej_meaning = _localized(BEEJ_MANTRA_MEANINGS.get(planet_code, {}), language)
    deity_meaning = _localized(deity_row["meanings"], language)
    return {
        "lord": planet_code,
        "role": role,
        "planet": planet_row["planet"],
        "deity": deity_row["deity"],
        "day": planet_row["day"],
        "language": language,
        "beej_label": "Beej Mantra",
        "beej_mantra": beej_mantra,
        "beej_transliteration": beej_transliteration,
        "beej_meaning": beej_meaning,
        "beej": {
            "label": "Beej Mantra",
            "mantra": beej_mantra,
            "transliteration": beej_transliteration,
            "meaning": beej_meaning,
        },
        "deity_label": "Deity Mantra",
        "deity_mantra": deity_row["mantra"],
        "deity_transliteration": deity_row["transliteration"],
        "deity_meaning": deity_meaning,
        "deity_specific": {
            "label": "Deity Mantra",
            "mantra": deity_row["mantra"],
            "transliteration": deity_row["transliteration"],
            "meaning": deity_meaning,
        },
        "extra_guidance": planet_row.get("extra_guidance", []),
    }


def remedies_for_dasha(mahadasha_lord=None, antardasha_lord=None, language="English"):
    remedies = []
    if mahadasha_lord:
        remedies.append(remedy_for_planet(mahadasha_lord, "Mahadasha lord", language))
    if antardasha_lord and antardasha_lord != mahadasha_lord:
        remedies.append(remedy_for_planet(antardasha_lord, "Antardasha lord", language))
    language = normalize_language(language)
    return {
        "language": language,
        "remedies": [remedy for remedy in remedies if remedy],
        "devotion_note": DEVOTION_NOTES[language],
    }
